/**
 * The optional GPU resizer module (port of V5's react-native-vision-camera-resizer), built on the core module's
 * Frame native buffers: a Vulkan compute pipeline (C++, libVisionCameraResizer.so) on Android, and a Metal compute
 * pipeline (Objective-C, libVisionCameraResizerNative.a) on iOS.
 */
kotlin {
    jvmToolchain(21)
    android {
        namespace = "me.nathanfallet.visioncamera.resizer"
        compileSdk = libs.versions.android.compileSdk.get().toInt()
        minSdk = libs.versions.android.minSdk.get().toInt()
        withHostTest {}
    }
    // The Metal pipeline, in Objective-C so that the per-frame CoreVideo textures are released right away: see
    // VisionCameraResizerNative.h.
    listOf(iosArm64(), iosSimulatorArm64()).forEach { target ->
        val library = buildIosNativeLibraries.getValue(target.name)
        target.compilations.getByName("main").cinterops.create("VisionCameraResizerNative") {
            includeDirs(file("src/iosMain/objc"))
            extraOpts("-libraryPath", library.get().outputDirectory.get().asFile.absolutePath)
            tasks.named(interopProcessingTaskName) { dependsOn(library) }
        }
    }

    compilerOptions {
        freeCompilerArgs.add("-Xexpect-actual-classes")
    }

    sourceSets {
        matching { it.name.startsWith("ios") }.configureEach {
            languageSettings.optIn("kotlinx.cinterop.ExperimentalForeignApi")
        }
        iosMain {
            kotlin.srcDir(generateMetalSource.map { it.outputDirectory })
        }
        commonMain.dependencies {
            api(projects.core)
        }
        commonTest.dependencies {
            implementation(libs.kotlin.test)
            implementation(libs.kotlinx.coroutines.test)
        }
    }
}

/**
 * Compiles src/androidMain/shaders/Resizer.comp to SPIR-V with the NDK's glslc (like V5's compile-shaders.gradle), as
 * a list of comma-separated words (`-mfmt=num`) that VulkanResizerShaderSpirv.cpp embeds in the library: V5 ships it
 * as an app asset instead.
 */
@CacheableTask
abstract class CompileResizerShaderTask : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val shaderDirectory: DirectoryProperty

    /** The Android SDK, containing the NDK in ndk/<ndkVersion>. */
    @get:Internal
    abstract val sdkDirectory: DirectoryProperty

    @get:Input
    abstract val ndkVersion: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @get:Inject
    abstract val execOperations: ExecOperations

    @TaskAction
    fun compile() {
        val ndk = sdkDirectory.get().asFile.resolve("ndk/${ndkVersion.get()}")
        if (!ndk.isDirectory) {
            throw GradleException(
                "NDK ${ndkVersion.get()} is not installed in $ndk, install it with: " +
                    "sdkmanager --install \"ndk;${ndkVersion.get()}\"",
            )
        }
        // shader-tools/<host>/glslc, e.g. darwin-x86_64 on every Mac.
        val glslc = ndk.resolve("shader-tools").listFiles().orEmpty()
            .flatMap { host -> listOf("glslc", "glslc.exe").map { host.resolve(it) } }
            .firstOrNull { it.exists() }
            ?: throw GradleException("glslc not found in the NDK's shader-tools at $ndk")
        val output = outputDirectory.get().asFile
        output.deleteRecursively()
        output.mkdirs()
        execOperations.exec {
            executable = glslc.absolutePath
            args(
                "-O",
                "-mfmt=num",
                shaderDirectory.file("Resizer.comp").get().asFile.absolutePath,
                "-o",
                output.resolve("Resizer.comp.spv.inc").absolutePath,
            )
        }
    }
}

/**
 * Compiles the JNI sources of src/androidMain/cpp (V5's Vulkan pipeline) into libVisionCameraResizer.so for every
 * Android ABI, with the NDK's clang (like core's libVisionCamera.so task).
 *
 * The Kotlin Multiplatform Android library plugin has no externalNativeBuild, so the library is built by this task
 * and added to the variant's jniLibs (see androidComponents below), which packages it in the AAR's jni/<abi>/.
 * Unlike core's sources, V5's pipeline uses the C++ standard library and exceptions: libc++ is linked statically, with
 * its symbols hidden, so there is no libc++_shared.so to ship or to conflict with the app's.
 */
@CacheableTask
abstract class BuildNativeLibrariesTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sources: ConfigurableFileCollection

    /** The include directories: the sources' root, and the generated headers (the compiled shader). */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val includeDirectories: ConfigurableFileCollection

    /** The Android SDK, containing the NDK in ndk/<ndkVersion>. */
    @get:Internal
    abstract val sdkDirectory: DirectoryProperty

    @get:Input
    abstract val ndkVersion: Property<String>

    @get:Input
    abstract val minSdk: Property<Int>

    @get:Input
    abstract val libraryName: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @get:Inject
    abstract val execOperations: ExecOperations

    @TaskAction
    fun build() {
        val ndk = sdkDirectory.get().asFile.resolve("ndk/${ndkVersion.get()}")
        if (!ndk.isDirectory) {
            throw GradleException(
                "NDK ${ndkVersion.get()} is not installed in $ndk, install it with: " +
                    "sdkmanager --install \"ndk;${ndkVersion.get()}\"",
            )
        }
        val prebuilt = ndk.resolve("toolchains/llvm/prebuilt").listFiles()?.singleOrNull { it.isDirectory }
            ?: throw GradleException("No LLVM toolchain found in the NDK at $ndk")
        val clang = listOf("clang++", "clang++.exe").map { prebuilt.resolve("bin/$it") }.firstOrNull { it.exists() }
            ?: throw GradleException("clang++ not found in $prebuilt")
        val cppSources = sources.files.filter { it.extension == "cpp" }.sorted().map { it.absolutePath }
        val includes = includeDirectories.files.map { "-I${it.absolutePath}" }
        val output = outputDirectory.get().asFile
        output.deleteRecursively()
        val library = "lib${libraryName.get()}.so"
        ABI_TARGETS.forEach { (abi, target) ->
            val abiDirectory = output.resolve(abi).apply { mkdirs() }
            execOperations.exec {
                executable = clang.absolutePath
                args(
                    "--target=$target${minSdk.get()}",
                    "-std=c++20",
                    "-O2",
                    "-fPIC",
                    "-Wall",
                    "-Wextra",
                    "-Wswitch-enum",
                    "-Werror",
                    "-fstack-protector-all",
                    "-fvisibility=hidden",
                    "-fvisibility-inlines-hidden",
                    "-ffunction-sections",
                    "-fdata-sections",
                    "-static-libstdc++",
                    "-shared",
                    "-Wl,-soname,$library",
                    // 16 KB page sizes support (Android 15+)
                    "-Wl,-z,max-page-size=16384",
                    "-Wl,--no-undefined",
                    "-Wl,--gc-sections",
                    "-Wl,--exclude-libs,ALL",
                    "-Wl,--build-id=sha1",
                    "-o",
                    abiDirectory.resolve(library).absolutePath,
                )
                args(includes)
                args(cppSources)
                args("-lvulkan", "-landroid", "-llog")
            }
        }
    }

    private companion object {
        /** The Android ABIs, and their clang target triple (the API level is appended). */
        val ABI_TARGETS = mapOf(
            "arm64-v8a" to "aarch64-linux-android",
            "armeabi-v7a" to "armv7a-linux-androideabi",
            "x86_64" to "x86_64-linux-android",
            "x86" to "i686-linux-android",
        )
    }
}

val compileResizerShader = tasks.register<CompileResizerShaderTask>("compileResizerShader") {
    description = "Compiles the resizer's Vulkan compute shader to SPIR-V with the NDK's glslc."
    shaderDirectory.set(layout.projectDirectory.dir("src/androidMain/shaders"))
    sdkDirectory.set(androidComponents.sdkComponents.sdkDirectory)
    ndkVersion.set(libs.versions.android.ndk)
    outputDirectory.set(layout.buildDirectory.dir("generated/shaders"))
}

val buildNativeLibraries = tasks.register<BuildNativeLibrariesTask>("buildNativeLibraries") {
    description = "Compiles libVisionCameraResizer.so (JNI, Vulkan) for every Android ABI with the NDK."
    sources.from(fileTree("src/androidMain/cpp"))
    includeDirectories.from(file("src/androidMain/cpp"), compileResizerShader.map { it.outputDirectory })
    // Pinned (gradle/libs.versions.toml), since the Kotlin Multiplatform Android library DSL has no ndkVersion.
    sdkDirectory.set(androidComponents.sdkComponents.sdkDirectory)
    ndkVersion.set(libs.versions.android.ndk)
    minSdk.set(libs.versions.android.minSdk.get().toInt())
    libraryName.set("VisionCameraResizer")
    outputDirectory.set(layout.buildDirectory.dir("generated/jniLibs"))
}

androidComponents {
    onVariants { variant ->
        val jniLibs = variant.sources.jniLibs
            ?: throw GradleException("The ${variant.name} variant has no jniLibs sources to add libVisionCameraResizer.so to")
        jniLibs.addGeneratedSourceDirectory(buildNativeLibraries, BuildNativeLibrariesTask::outputDirectory)
    }
}

