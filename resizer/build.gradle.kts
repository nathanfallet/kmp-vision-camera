/**
 * Compiles the Objective-C sources of src/iosMain/objc into a static library for one iOS target, with Xcode's clang
 * (same as core's task). cinterop (src/nativeInterop/cinterop/VisionCameraResizerNative.def) embeds the library in the
 * target's klib, so apps link it without any setup.
 */
@CacheableTask
abstract class BuildIosNativeLibraryTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sources: ConfigurableFileCollection

    /** The SDK, `iphoneos` or `iphonesimulator`. */
    @get:Input
    abstract val sdk: Property<String>

    /** The clang target triple, e.g. `arm64-apple-ios15.0-simulator`. */
    @get:Input
    abstract val targetTriple: Property<String>

    @get:Input
    abstract val libraryName: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @get:Inject
    abstract val execOperations: ExecOperations

    @TaskAction
    fun build() {
        val output = outputDirectory.get().asFile
        output.deleteRecursively()
        output.mkdirs()
        val objects = sources.files.filter { it.extension == "m" }.sorted().map { source ->
            output.resolve("${source.nameWithoutExtension}.o").also { objectFile ->
                execOperations.exec {
                    commandLine(
                        "xcrun", "--sdk", sdk.get(), "clang",
                        "-target", targetTriple.get(),
                        "-fobjc-arc",
                        "-fmodules",
                        "-O2",
                        "-Wall",
                        "-Werror",
                        "-c", source.absolutePath,
                        "-o", objectFile.absolutePath,
                    )
                }
            }
        }
        execOperations.exec {
            commandLine("xcrun", "libtool", "-static", "-o", output.resolve("lib${libraryName.get()}.a").absolutePath)
            args(objects.map { it.absolutePath })
        }
    }
}

/**
 * Generates a Kotlin constant with the source of src/iosMain/metal/ResizerKernels.metal, which the iOS pipeline
 * compiles at runtime: a klib cannot ship V5's precompiled metallib bundle.
 */
@CacheableTask
abstract class GenerateMetalSourceTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val metalSource: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val source = metalSource.get().asFile.readText()
        require("\"\"\"" !in source) { "The Metal source must not contain triple quotes." }
        val output = outputDirectory.get().asFile
        output.deleteRecursively()
        val file = output.resolve("me/nathanfallet/visioncamera/resizer/ResizerKernelsSource.kt")
        file.parentFile.mkdirs()
        file.writeText(
            buildString {
                appendLine("// Generated by the resizer's generateMetalSource task from src/iosMain/metal/ResizerKernels.metal.")
                appendLine("package me.nathanfallet.visioncamera.resizer")
                appendLine()
                appendLine("/** The source of ResizerKernels.metal, the resizer's Metal kernels. */")
                append("internal const val RESIZER_KERNELS_SOURCE: String = \"\"\"")
                append(source.replace("$", "\${'$'}"))
                appendLine("\"\"\"")
            },
        )
    }
}

/** The minimum iOS version of libVisionCameraResizerNative.a: Kotlin/Native's default. */
val iosMinVersion = "15.0"

/** The tasks building libVisionCameraResizerNative.a, by Kotlin target name. */
val buildIosNativeLibraries = mapOf(
    "iosArm64" to ("iphoneos" to "arm64-apple-ios$iosMinVersion"),
    "iosSimulatorArm64" to ("iphonesimulator" to "arm64-apple-ios$iosMinVersion-simulator"),
).mapValues { (targetName, platform) ->
    tasks.register<BuildIosNativeLibraryTask>("buildIosNativeLibrary${targetName.replaceFirstChar { it.uppercase() }}") {
        description = "Compiles libVisionCameraResizerNative.a (Objective-C) for $targetName with Xcode's clang."
        sources.from(fileTree("src/iosMain/objc"))
        sdk.set(platform.first)
        targetTriple.set(platform.second)
        libraryName.set("VisionCameraResizerNative")
        outputDirectory.set(layout.buildDirectory.dir("generated/iosNativeLibraries/$targetName"))
        // Like the iOS cinterop and compilations, which are skipped on other hosts (e.g. the Linux Android build).
        onlyIf("Xcode is only available on macOS") { System.getProperty("os.name").startsWith("Mac") }
    }
}

